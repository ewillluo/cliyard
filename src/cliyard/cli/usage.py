"""``cliyard usage`` — Generate project AGENTS.md with framework reference.

Outputs a static document covering cliyard's subcommands, YAML spec
conventions, plugin system, and flow orchestration — no spec directory
needed, works from any directory.
"""

from __future__ import annotations

from pathlib import Path

import click


def generate() -> str:
    """Generate AGENTS.md content for the current project."""
    lines: list[str] = []
    P = lines.append

    P("# Project Overview")
    P("")
    P("Generated by [cliyard](https://github.com/guolong123/cliyard) — ")
    P("a YAML-driven CLI framework for any REST API.")
    P("")
    P("Two usage modes:")
    P("- **Library mode**: `create_cli('./specs/')` → `click.Group` — dynamic, no gen step")
    P("- **Gen mode**: `cliyard gen --name mycli --defs-path ./specs/` → pip-installable package")
    P("")

    # ── CLI commands ──
    P("## CLI Commands")
    P("")
    P("| Command | Description |")
    P("|---------|-------------|")
    P("| `auth add` | Add authentication profile |")
    P("| `auth switch` | Switch active profile |")
    P("| `auth rm` | Remove profile |")
    P("| `auth status` | Show current profile |")
    P("| `gen` | Generate standalone CLI from YAML specs |")
    P("| `usage` | Generate this AGENTS.md |")
    P("| `<resource> <method>` | Dynamic commands from YAML specs |")
    P("| `flow-run <flow>` | Run orchestrated workflow |")
    P("")

    # ── Directory structure ──
    P("## Spec Directory Structure")
    P("")
    P("```")
    P("specs/")
    P("├── _auth.yaml              # Service config (server, auth)")
    P("├── _groups.yaml            # (optional) Group definitions")
    P("├── _flows.yaml             # (optional) Flow orchestration index")
    P("├── resources/              # Resource YAML files")
    P("│   ├── repos.yaml")
    P("│   └── ...")
    P("├── flows/                  # (optional) Flow step definitions")
    P("│   ├── _flow_create_repo.yaml")
    P("│   └── ...")
    P("└── plugins/                # Python plugins")
    P("    └── *.py")
    P("```")
    P("")

    # ── _auth.yaml ──
    P("## Service Config (`_auth.yaml`)")
    P("")
    P("```yaml")
    P("name: myapi")
    P("server:")
    P("  - name: main")
    P("    base_url: https://api.example.com")
    P("    prefix: /api/v1")
    P("auth:")
    P("  steps:")
    P("    - name: login")
    P("      type: login")
    P("      config:")
    P("        endpoint: /auth/login")
    P("        method: POST")
    P("        body:")
    P("          username: '{{ env(\"USER\") }}'")
    P("      extract:")
    P("        token: $.token")
    P("    - name: inject")
    P("      type: inject")
    P("      config:")
    P("        source: login")
    P("        into: header")
    P("        name: Authorization")
    P("        prefix: 'Bearer '")
    P("  persist:")
    P("    to: cliyard-config")
    P("    fields:")
    P("      token:")
    P("        from: login")
    P("```")
    P("")

    # ── Resource YAML ──
    P("## Resource YAML")
    P("")
    P("```yaml")
    P("description: 仓库管理")
    P("path: repos")
    P("methods:")
    P("  list:")
    P("    http:")
    P("      method: GET")
    P("    params:")
    P("      query:")
    P("        - name: pageNo")
    P("          field: pageNo")
    P("          type: int")
    P("          default: 1")
    P("    output:")
    P("      items_path: $.repos")
    P("      fields:")
    P("        - name: name")
    P("          alias: 仓库名称")
    P("  create:")
    P("    http:")
    P("      method: POST")
    P("      path: repos/{{ name }}")
    P("    params:")
    P("      body:")
    P("        - name: name")
    P("          type: string")
    P("          required: true")
    P("    request_body:")
    P("      name: '{{ name }}'")
    P("      type: '{{ repo_type | default(\"EVENTS\") }}'")
    P("```")
    P("")

    # ── Param conventions ──
    P("## Parameter Conventions")
    P("")
    P("| YAML `name` | CLI option | API param (via `field`) |")
    P("|-------------|-----------|------------------------|")
    P("| `with_doc_size` | `--with-doc-size` | `withDocSize` |")
    P("| `pageNo` | `--page-no` | `pageNo` |")
    P("| `asset_id` | `--asset-id` | `assetId` |")
    P("")
    P("### Type Mapping")
    P("")
    P("| YAML type | Click type | Notes |")
    P("|-----------|-----------|-------|")
    P("| `string` | `str` | |")
    P("| `int` | `int` | |")
    P("| `float` | `float` | |")
    P("| `bool` | `is_flag=True` | `--flag` / `--no-flag` |")
    P("| `enum` | `click.Choice` | Requires `choices:` |")
    P("| `file` | `click.Path` | `--file PATH` |")
    P("")
    P("### Constraints")
    P("")
    P("| Field | Constraints |")
    P("|-------|------------|")
    P("| `type: string` | `pattern`, `min_length`, `max_length` |")
    P("| `type: int` | `min`, `max` |")
    P("| `type: float` | `min`, `max` |")
    P("| `multiple: true` | Allow `--tag a --tag b` → tuple |")
    P("| `depends_on` | `field: x, eq: v` → required when x=v |")
    P("| `argument: true` | Force positional argument |")
    P("")

    # ── Plugin system ──
    P("## Plugin System")
    P("")
    P("Seven extension points, registered via decorator:")
    P("")
    P("| Decorator | Purpose |")
    P("|-----------|---------|")
    P("| `@register_step_type(\"name\")` | Custom flow orchestration step |")
    P("| `@register_auth_step(\"name\")` | Custom authentication step |")
    P("| `@register_field_type(\"name\")` | Custom field validator |")
    P("| `@register_hook(\"name\")` | Pre/post request hook |")
    P("| `@register_method(\"name\")` | Multi-step business method |")
    P("| `@register_command(\"name\")` | Top-level Click command |")
    P("| `@register_field_resolver(\"name\")` | Dynamic field value resolver |")
    P("")
    P("Plugins are auto-discovered from three sources:")
    P("")
    P("1. **Entry points**: `cliyard.auth`, `cliyard.types`, `cliyard.hooks`, `cliyard.steps`")
    P("2. **Spec directory**: `specs/plugins/*.py` and `{spec_dir.parent}/plugins/`")
    P("3. **Global**: `~/.cliyard/plugins/*.py`")
    P("")

    # ── Flow orchestration ──
    P("## Flow Orchestration")
    P("")
    P("Multi-step workflow defined in `_flows.yaml`. Steps run sequentially with")
    P("support for conditional branching, loops, and lifecycle hooks.")
    P("")
    P("### Structure")
    P("")
    P("```")
    P("specs/")
    P("├── flows/")
    P("│   ├── _flows.yaml              # Registration index (command, params)")
    P("│   ├── _flow_create_repo.yaml    # Step definitions")
    P("│   └── ...")
    P("```")
    P("")
    P("### Registration (`_flows.yaml`)")
    P("")
    P("```yaml")
    P("flows:")
    P("  create_repo:")
    P("    command: create-repo")
    P("    description: 创建仓库")
    P("    steps: _flow_create_repo.yaml")
    P("    params:")
    P("      query:")
    P("        - name: name")
    P("          type: string")
    P("          required: true")
    P("```")
    P("")
    P("### Steps (`_flow_create_repo.yaml`)")
    P("")
    P("```yaml")
    P("steps:")
    P("  - id: check_repo")
    P("    description: 查询仓库是否存在")
    P("    use: repo.list")
    P("    params:")
    P("      pageSize: 100")
    P("    extract:")
    P("      repos: $.repos")
    P("")
    P("  - id: decision")
    P("    on_result:")
    P("      - if: condition")
    P("        then:")
    P("          - type: echo")
    P("            message: 'exists'")
    P("          - action: return")
    P("      - else:")
    P("          steps:")
    P("            - id: do_create")
    P("              use: repo.create")
    P("```")
    P("")
    P("### Step types")
    P("")
    P("| Type | Usage |")
    P("|------|-------|")
    P("| `use: resource.method` | Invoke an existing CLI command |")
    P("| `type: plugin:xxx` | Execute a registered plugin step |")
    P("| `type: echo` | Print a message |")
    P("| `action: return/abort/warn/skip` | Control flow |")
    P("| `include: _flow_file.yaml` | Include steps from another file |")
    P("")
    P("### Loops")
    P("")
    P("```yaml")
    P("# Iterate over list")
    P("- id: batch")
    P("  for_each:")
    P("    items: '{{ step.list.items }}'")
    P("    as: item")
    P("    steps:")
    P("      - id: process")
    P("        use: resource.method")
    P("")
    P("# Retry on failure")
    P("- id: deploy")
    P("  use: resource.method")
    P("  retry:")
    P("    max_attempts: 3")
    P("    delay: 2")
    P("    backoff: 2")
    P("")
    P("# Poll until condition met")
    P("- id: wait")
    P("  use: resource.get")
    P("  until:")
    P("    max_iterations: 30")
    P("    interval: 5")
    P("    condition: '{{ step.wait.status == \"RUNNING\" }}'")
    P("```")
    P("")
    P("### Lifecycle hooks")
    P("")
    P("```yaml")
    P("flows:")
    P("  deploy_app:")
    P("    hooks:")
    P("      on_start: [validate_env]")
    P("      on_end: [notify_result]")
    P("      on_failure: [notify_failure]")
    P("    steps: _flow_deploy.yaml")
    P("```")
    P("")

    return "\n".join(lines)


@click.command()
@click.option(
    "-o",
    "--output",
    default=None,
    type=click.Path(file_okay=False, resolve_path=False),
    help="Output file path (default: stdout)",
)
def usage(output: str | None) -> None:
    """Generate AGENTS.md for the current project.

    Outputs a static reference covering cliyard's subcommands, YAML spec
    conventions, plugin system, and flow orchestration.  No spec directory
    needed — works from any directory.
    """
    docs = generate()

    if output:
        out_path = Path(output)
        out_path.write_text(docs, encoding="utf-8")
        click.echo(f"Written to {out_path}", err=True)
    else:
        click.echo(docs)
